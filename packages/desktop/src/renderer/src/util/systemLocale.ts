export const systemTextForLocale = (
  locale: string,
  key: SystemTextKey,
  params: SystemTextParams = {}
): string => {
  const messages: Record<SystemTextKey, string> = locale.toLowerCase().startsWith('zh') ? zh : en
  return Object.entries(params).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[key]
  )
}
